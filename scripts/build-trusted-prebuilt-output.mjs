import { mkdir, rm, writeFile } from 'node:fs/promises';

const outputRoot = '.vercel/output';
const functionRoot = `${outputRoot}/functions/api/workflow-manifest.func`;

await rm(outputRoot, { recursive: true, force: true });

await mkdir(`${functionRoot}/api`, { recursive: true });
await mkdir(`${outputRoot}/static`, { recursive: true });

await writeFile(
  `${outputRoot}/config.json`,
  JSON.stringify(
    {
      version: 3,
      routes: [
        { handle: 'filesystem' },
        { src: '^/api(/.*)?$', status: 404 },
        { handle: 'error' },
        { status: 404, src: '^(?!/api).*$', dest: '/404.html' },
        { handle: 'miss' },
        { src: '^/api/(.+)(?:\\.(?:js))$', dest: '/api/$1', check: true },
      ],
      crons: [],
    },
    null,
    2,
  ),
);

await writeFile(
  `${outputRoot}/builds.json`,
  JSON.stringify(
    {
      '//': 'Trusted build output generated by the base workflow for the metadata-only filePathMap proof.',
      target: 'preview',
      argv: ['node', 'scripts/build-trusted-prebuilt-output.mjs'],
      cliVersion: '54.21.1',
      builds: [],
    },
    null,
    2,
  ),
);

await writeFile(
  `${functionRoot}/api/workflow-manifest.js`,
  `const { readFile } = require('node:fs/promises');
const { join } = require('node:path');

module.exports = async function handler(_req, res) {
  const manifestPath = join(process.cwd(), '.nestjs/workflow/manifest.json');

  try {
    const body = await readFile(manifestPath, 'utf8');
    res.setHeader('content-type', 'text/plain; charset=utf-8');
    res.statusCode = 200;
    res.end(body);
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      res.statusCode = 404;
      res.end('MISSING_MANIFEST');
      return;
    }

    res.statusCode = 500;
    res.end(\`READ_ERROR:\${error && error.code ? error.code : 'unknown'}\`);
  }
};
`,
);

await writeFile(
  `${functionRoot}/package.json`,
  JSON.stringify(
    {
      name: 'trusted-workflow-manifest-reader',
      version: '0.0.0',
      private: true,
      type: 'commonjs',
    },
    null,
    2,
  ),
);

await writeFile(
  `${functionRoot}/.vc-config.json`,
  JSON.stringify(
    {
      handler: 'api/workflow-manifest.js',
      runtime: 'nodejs24.x',
      architecture: 'x86_64',
      environment: {},
      shouldDisableAutomaticFetchInstrumentation: false,
      launcherType: 'Nodejs',
      shouldAddHelpers: true,
      shouldAddSourcemapSupport: false,
      awsLambdaHandler: '',
    },
    null,
    2,
  ),
);

